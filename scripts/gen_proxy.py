#!/usr/bin/env python3
"""Emit x86 register-preserving lazy tail thunks (MSVC/clang-cl inline asm).

One proxy per proxy/<dll>/exports.txt. Exports get ordinals in file order, so
list them in the real DLL's ordinal order: games may import by ordinal.
"""
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]


def generate(directory):
    dll = directory.name
    names = [line.strip() for line in (directory / 'exports.txt').read_text().splitlines() if line.strip()]
    source = ['// Generated by scripts/gen_proxy.py', '#include <windows.h>',
              f'extern "C" void* appx_targets[{len(names)}];', 'extern "C" void __cdecl appx_resolve(unsigned index);']
    definition = [f'LIBRARY {dll}', 'EXPORTS']
    for index, name in enumerate(names):
        source += [f'extern "C" __declspec(naked) void proxy_{name}() {{',
                   '  __asm {', '    pushfd', '    pushad', f'    push {index}',
                   '    call appx_resolve', '    add esp, 4', '    popad', '    popfd',
                   f'    jmp dword ptr [appx_targets + {index * 4}]', '  }', '}']
        definition += [f'  {name}=proxy_{name} @{index + 1}']
    source += ['extern "C" const char* appx_export_names[] = {']
    source += [f'  "{name}",' for name in names]
    source += ['};', f'extern "C" void* appx_targets[{len(names)}] = {{}};',
               f'extern "C" const unsigned appx_export_count = {len(names)};']
    header = ['// Generated by scripts/gen_proxy.py', '#pragma once',
              f'#define APPX_PROXY_INTERNAL "{dll}"', f'#define APPX_PROXY_FILE "{dll}.dll"',
              f'#define APPX_PROXY_FILE_W L"{dll}.dll"',
              f'#define APPX_PROXY_DESCRIPTION "appx-portable ({dll} proxy)"']
    (directory / 'thunks.cpp').write_bytes(('\n'.join(source) + '\n').encode())  # LF on every platform
    (directory / 'proxy.def').write_bytes(('\n'.join(definition) + '\n').encode())  # LF on every platform
    (directory / 'proxy_names.h').write_bytes(('\n'.join(header) + '\n').encode())  # LF on every platform


for exports in sorted((root / 'proxy').glob('*/exports.txt')):
    generate(exports.parent)
